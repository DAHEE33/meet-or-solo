/**
 * 이용약관과 개인정보처리방침 원문.
 *
 * 동의 체크박스 옆의 `전문 보기`가 이 데이터를 그대로 띄운다. 동의 시점에 원문을 보여주는 것이
 * 동의의 근거이므로, 문구를 고치면 `version`을 올리고 서버 `MemberConsentType.currentVersion()`도
 * 함께 올려야 한다. 두 값이 어긋나면 "무엇에 동의했는지"를 나중에 특정할 수 없다.
 *
 * 내용은 실제 구현에서 뽑았다. 없는 기능을 적지 않고, 하는 일을 빠뜨리지도 않는다.
 * - 체크인은 좌표를 전송받아 축제와의 거리만 계산하고 좌표는 저장하지 않는다
 *   (`FestivalCheckinService`, `festival_checkins`에 `distance_meters`만 있다).
 * - 취향 글만 국외(OpenAI, 미국)로 전송된다(`MemberPreferenceEmbeddingService`).
 * - 성별과 연령대는 암호화해 저장한다(`ProfileFieldCrypto`, `*_encrypted` 컬럼).
 * - 탈퇴는 물리 삭제가 아니라 개인정보 삭제 + 이력 보존이다(`Member.withdraw`).
 *
 * TODO(운영): 공개 운영 전에 아래 값을 운영자가 확정해야 한다.
 * 1. 개인정보 보호책임자의 성명·직책 (현재는 "서비스 운영자"로만 표기)
 * 2. 신고·제재 기록의 구체적 보유 기간 (현재는 "안전 목적 보관"으로만 표기)
 * 3. 프로필 이미지를 저장하는 오브젝트 스토리지 사업자명 (환경설정 값이라 코드에서 알 수 없다)
 * 4. 만 14세 이상 가입 제한을 유지할지 (현재 코드에는 연령 확인 절차가 없다)
 */

export type LegalDocumentId = 'TERMS' | 'PRIVACY';

export interface LegalDocumentSection {
  heading: string;
  paragraphs: string[];
}

export interface LegalDocument {
  id: LegalDocumentId;
  title: string;
  /** 서버 `MemberConsentType`의 `currentVersion`과 같아야 한다. */
  version: string;
  effectiveDate: string;
  sections: LegalDocumentSection[];
}

/** 서버 `MemberConsentType.TERMS/PRIVACY.currentVersion()`과 맞춘 값. */
export const LEGAL_DOCUMENT_VERSION = '1.0';

export const LEGAL_DOCUMENT_EFFECTIVE_DATE = '2026-09-10';

const CONTACT_UNSET_NOTICE = '문의 이메일이 설정되지 않았습니다(VITE_SUPPORT_CONTACT_EMAIL)';

/**
 * 문의처 이메일. backend의 `SUPPORT_CONTACT_EMAIL`과 같은 값을 넣는다.
 *
 * 값이 비면 문구를 조용히 지우지 않고 설정되지 않았다는 사실을 그대로 보여준다. 제재 안내에서
 * 환경변수 누락이 문구를 소리 없이 없앴던 것과 같은 실수를 반복하지 않기 위한 것이다.
 */
export function supportContactEmail(): string {
  const value = import.meta.env.VITE_SUPPORT_CONTACT_EMAIL;
  return typeof value === 'string' && value.trim().length > 0
    ? value.trim()
    : CONTACT_UNSET_NOTICE;
}

